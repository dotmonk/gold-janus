import * as fs from "fs";
import * as path from "path";
import type { ParamInfo, RouteInfo } from "./discovery";

const CLIENT_RUNTIME = fs.readFileSync(path.join(__dirname, "clientRuntime.js"), "utf8");

function clientParamType(p: ParamInfo): string {
  if (p.kind !== "file") return p.typeText;
  return p.isFileList ? "(File | Blob)[]" : "File | Blob";
}

export function normalizeClientBaseUrl(base: string): string {
  return base.replace(/\/+$/, "");
}

function jsParamList(route: RouteInfo): string {
  return route.paramInfos.map((p) => p.name).join(", ");
}

function jsObject(names: string[]): string {
  return names.length ? `{ ${names.join(", ")} }` : "{}";
}

function dtsParamSig(p: ParamInfo): string {
  const t = clientParamType(p);
  if (!p.isOptional) return `${p.name}: ${t}`;
  return `${p.name}?: ${t}`;
}

function dtsSseMethod(route: RouteInfo): string {
  const evType = route.sseEventType ?? "unknown";
  const dataSig = route.paramInfos.map(dtsParamSig).join(", ");
  const sep = dataSig ? ", " : "";
  return (
    `    ${route.methodName}(${dataSig}${sep}` +
    `callback: (data: ${evType}) => void, onError?: (error: GoldClientError) => void): () => void;`
  );
}

function dtsRequestMethod(route: RouteInfo): string {
  const paramSig = route.paramInfos.map(dtsParamSig).join(", ");
  return `    ${route.methodName}(${paramSig}): ApiResponse<${route.returnTypeText}>;`;
}

function jsSseMethod(route: RouteInfo): string {
  const params = jsParamList(route);
  const sep = params ? ", " : "";
  const args = jsObject(route.paramInfos.map((p) => p.name));
  return (
    `    ${route.methodName}(${params}${sep}callback, onError) {\n` +
    `      return _stream(${JSON.stringify(route.dispatchKey)}, ${args}, callback, onError);\n` +
    `    },`
  );
}

function jsRequestMethod(route: RouteInfo): string {
  const params = jsParamList(route);
  const method = JSON.stringify(route.dispatchKey);
  const hasFile = route.paramInfos.some((p) => p.kind === "file");
  const body = hasFile
    ? `_form(${jsObject(route.paramInfos.filter((p) => p.kind === "file").map((p) => p.name))}, ` +
      `${jsObject(route.paramInfos.filter((p) => p.kind !== "file").map((p) => p.name))})`
    : `JSON.stringify(${jsObject(route.paramInfos.map((p) => p.name))})`;
  return (
    `    ${route.methodName}(${params}) {\n` +
    `      return _call(${method}, ${body});\n` +
    `    },`
  );
}

export function clientDtsPath(jsPath: string): string {
  return jsPath.replace(/\.js$/i, "") + ".d.ts";
}

export function clientJsPath(generatedClientPath: string): string {
  return generatedClientPath.endsWith(".js")
    ? generatedClientPath
    : generatedClientPath.replace(/\.tsx?$/i, "") + ".js";
}

export async function generateClient(
  routes: RouteInfo[],
  typeDeclarations: string[],
  generatedClientPath: string,
  clientBaseUrl: string
): Promise<void> {
  const jsPath = clientJsPath(generatedClientPath);
  const dtsPath = clientDtsPath(jsPath);

  const stamp = new Date().toISOString();
  const jsLines: string[] = [
    `// AUTO-GENERATED by Gild — do not edit manually`,
    `// Generated on ${stamp}`,
    ``,
    `const _base = ${JSON.stringify(clientBaseUrl)};`,
    ``,
    CLIENT_RUNTIME,
  ];

  const jsByNamespace: Record<string, string[]> = {};
  const dtsByNamespace: Record<string, string[]> = {};
  for (const route of routes) {
    (jsByNamespace[route.namespaceName] ??= []).push(
      route.isSSE ? jsSseMethod(route) : jsRequestMethod(route)
    );
    (dtsByNamespace[route.namespaceName] ??= []).push(
      route.isSSE ? dtsSseMethod(route) : dtsRequestMethod(route)
    );
  }

  jsLines.push(`const _api = {`);
  for (const [ns, methods] of Object.entries(jsByNamespace))
    jsLines.push(`  ${ns}: {`, ...methods, `  },`);
  jsLines.push(`};`, ``, `export default _api;`);
  for (const ns of Object.keys(jsByNamespace))
    jsLines.push(`export const ${ns} = _api.${ns};`);

  const dtsLines: string[] = [
    `// AUTO-GENERATED by Gild — do not edit manually`,
    `// Generated on ${stamp}`,
    ``,
    ...typeDeclarations,
    `export type ApiResponse<T> = Promise<T>;`,
    `/** Rejection of a call, or a stream error: the server's message plus its HTTP status. */`,
    `export type GoldClientError = Error & { status?: number };`,
    ``,
  ];
  for (const [ns, methods] of Object.entries(dtsByNamespace)) {
    dtsLines.push(`export declare const ${ns}: {`);
    dtsLines.push(...methods);
    dtsLines.push(`};`, ``);
  }
  dtsLines.push(`declare const _api: {`);
  for (const ns of Object.keys(dtsByNamespace))
    dtsLines.push(`  ${ns}: typeof ${ns};`);
  dtsLines.push(`};`, ``, `export default _api;`);

  fs.mkdirSync(path.dirname(jsPath), { recursive: true });
  fs.writeFileSync(jsPath, jsLines.join("\n"), "utf-8");
  fs.writeFileSync(dtsPath, dtsLines.join("\n"), "utf-8");
}
